def f(x):
    return -2 * np.sin(np.sqrt(abs(x / 2 + 10))) - x * np.sin(np.sqrt(abs(x - 10)))


def df(x):
    """
    Аналитическая производная f1(x).
    Не определена в x = -20 и x = 10 (особые точки из-за abs).
    Возвращает вещественное число; в особых точках — приближение.
    """
    eps = 1e-15  # порог для избежания деления на ноль

    # Часть 1: d/dx [ -2 * sin(sqrt(|x/2 + 10|)) ]
    u = x / 2 + 10
    abs_u = abs(u)
    if abs_u < eps:
        term1 = 0.0  # или np.nan — но 0 безопаснее для численных методов
    else:
        sign_u = np.sign(u)
        sqrt_abs_u = np.sqrt(abs_u)
        term1 = -2 * np.cos(sqrt_abs_u) * (sign_u / 4) / sqrt_abs_u
        # Обоснование: d/dx sqrt(|u|) = (1/(2*sqrt(|u|))) * sign(u) * du/dx,
        # где du/dx = 1/2 → итого: sign(u) / (4 * sqrt(|u|))

    # Часть 2: d/dx [ -x * sin(sqrt(|x - 10|)) ] = -sin(...) - x * cos(...) * d/dx[sqrt(|x-10|)]
    v = x - 10
    abs_v = abs(v)
    if abs_v < eps:
        # При v ≈ 0: sqrt(|v|) ≈ 0, sin(0)=0, cos(0)=1, но производная sqrt(|v|) → ∞
        # Однако множитель x * ... может компенсировать? Лучше использовать предел.
        # Практически: ставим 0 или игнорируем особую точку.
        term2 = -np.sin(0.0)  # = 0
        term3 = 0.0
    else:
        sign_v = np.sign(v)
        sqrt_abs_v = np.sqrt(abs_v)
        term2 = -np.sin(sqrt_abs_v)
        term3 = -x * np.cos(sqrt_abs_v) * (sign_v / (2 * sqrt_abs_v))

    return term1 + term2 + term3



def f2(x):
    return x ** 2 - 10 * np.cos(0.5 * np.pi * x) - 110

def df2(x):
    """
    Аналитическая производная f2(x) = x^2 - 10*cos(0.5*pi*x) - 110.
    f2'(x) = 2x + 5*pi*sin(0.5*pi*x)
    """
    return 2 * x + 5 * np.pi * np.sin(0.5 * np.pi * x)

def bsearch(interval, tol):  # Определяет функцию поиска минимума методом бисекции (дихотомии).
    """
    Searches for minimum using bisection method (dichotomy).
    STRICTLY follows assignment: uses df(a) for stopping criterion.

    Args:
        interval: [a, b] - search interval
        tol: tolerance for stopping

    Returns:
        [xmin, fmin, neval, coords]
    """
    a, b = interval  # Распаковывает входной интервал [a, b] в переменные a и b.
    coords = []  # Инициализирует пустой список для хранения координат промежуточных точек поиска.
    neval = 0  # Счётчик количества вычислений производной (оценок градиента).
    L = b - a  # Вычисляет начальную длину интервала.
    g = df(a)  # Вычисляет производную в левой границе интервала a.
    neval += 1  # Увеличивает счётчик вычислений производной на 1.
    while (np.abs(L) > tol) and (np.abs(g) > tol):  # Пока длина интервала больше допуска И модуль производной в текущей точке больше допуска:
        x = (a + b) / 2  # Находит середину текущего интервала.
        coords.append(x)  # Добавляет эту точку в список координат для последующей визуализации.
        g = df(x)  # Вычисляет производную в найденной середине.
        neval += 1  # Увеличивает счётчик вычислений производной.
        if g > 0:  # Если производная положительна, функция возрастает → минимум слева.
            b = x  # Сдвигаем правую границу интервала к x.
        else:  # Если производная ≤ 0, функция не возрастает → минимум справа или в точке.
            a = x  # Сдвигаем левую границу интервала к x.
        L = b - a  # Обновляем длину интервала.
    xmin = (a + b) / 2  # После выхода из цикла — вычисляем приближённое положение минимума как середину финального интервала.
    fmin = f(xmin)  # Вычисляем значение функции в найденной точке минимума.
    neval += 1  # Увеличиваем счётчик ещё на 1 за вычисление f(xmin).
    answer_ = [xmin, fmin, neval, coords]  # Формируем результат: координата минимума, значение функции, число вычислений, список точек.
    return answer_  # Возвращает результат в виде списка.


def bisectionsearch2slides(interval, coords):  # Функция для визуализации процесса поиска минимума.
    # make plot
    t1 = np.arange(interval[0], interval[1], 0.001)  # Создаёт массив значений x от начала до конца интервала с шагом 0.001.
    fig, ax = plt.subplots()  # Создаёт новую фигуру и оси для графика.
    plt.plot(t1, f(t1))  # Рисует график функции f(x) на заданном интервале.
    plt.xlabel('x')  # Подписывает ось X как 'x'.
    plt.ylabel('y')  # Подписывает ось Y как 'y'.
    fig.savefig('plot.png')  # Сохраняет график в файл 'plot.png'.
    print("<img width=\"550px\" src=\"/resources/plot.png\">")  # Выводит HTML-тег для отображения графика в веб-интерфейсе.

    nfigs = min([10, len(coords)])  # Ограничивает количество выводимых промежуточных графиков до 10 или меньше, если точек меньше.
    for i in range(nfigs):  # Цикл по первым nfigs точкам поиска.
        plt.plot(coords[i], f(coords[i]), 'ro')  # Наносит i-ю точку поиска красным кружком ('ro').
        name = "plot" + str(i) + ".png"  # Формирует имя файла для i-го графика.
        fig.savefig(name)  # Сохраняет текущее состояние графика в файл с этим именем.
        ad = "<img width=\"550px\" src=\"/resources/" + name + "\">"  # Формирует HTML-тег для отображения этого графика.
        print(ad)  # Выводит HTML-тег в консоль (или веб-ответ).

    plt.plot(coords[-1], f(coords[-1]), 'bo')  # Наносит последнюю точку поиска синим кружком ('bo') — финальное приближение.
    fig.savefig('plotFin.png')  # Сохраняет финальный график в файл 'plotFin.png'.
    print("Final:")  # Выводит заголовок перед финальным графиком.
    print("<img width=\"550px\" src=\"/resources/plotFin.png\">")  # Выводит HTML-тег для финального графика.


def main():  # Основная функция программы.
    print("Find:")  # Выводит сообщение о начале поиска.
    interval = [-2, 10]  # Задаёт начальный интервал поиска минимума.
    tol = 1e-10  # Задаёт точность остановки алгоритма (очень малое число).
    [xmin, f, neval, coords] = bsearch(interval, tol)  # Вызывает функцию поиска минимума и получает результат.
    print([xmin, f, neval])  # Выводит найденный минимум, значение функции в нём и число вычислений.
    bisectionsearch2slides(interval, coords)  # Вызывает функцию визуализации процесса поиска.

if __name__ == '__main__':  # Проверяет, запущен ли скрипт напрямую (а не импортирован как модуль).
    main()  # Если да — запускает основную функцию.